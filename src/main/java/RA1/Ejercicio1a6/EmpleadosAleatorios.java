package RA1.Ejercicio1a6;

public class EmpleadosAleatorios {
    int id;
    String apellido;
    int departamento;
    double salario;

    public EmpleadosAleatorios(int id, String apellido, int departamento, double salario) {
        this.id = id;
        this.apellido = apellido;
        this.departamento = departamento;
        this.salario = salario;
    }
}
